//! Render `MIGRATIONS.md`: the current schema, then every migration with its analysis.
//!
//! The output is deterministic (no timestamps, no absolute paths) so `rustable check` can
//! compare it byte-for-byte with the committed file.

use std::fmt::Write;

use crate::analysis::Compat;
use crate::project::{MigrationReport, Project};
use crate::schema::{Schema, Table};
use crate::undo::GeneratedUndo;

#[must_use]
pub fn migrations_md(project: &Project, title: &str) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "# {title}\n");
    let _ = writeln!(
        out,
        "_Generated by `rustable generate` ({} migrations, dialect `{}`). Do not edit by hand._\n",
        project.migrations.len(),
        project.dialect
    );

    out.push_str("## Current State\n\n");
    current_state(&project.schema, &mut out);

    out.push_str("## Migrations\n\n");
    for m in &project.migrations {
        migration(m, &mut out);
    }
    out
}

fn current_state(schema: &Schema, out: &mut String) {
    if schema.tables.is_empty() && schema.views.is_empty() && schema.enums.is_empty() {
        out.push_str("_No tables yet._\n\n");
        return;
    }
    for table in &schema.tables {
        table_section(table, out);
    }
    if !schema.views.is_empty() {
        out.push_str("### Views\n\n");
        for v in &schema.views {
            let _ = writeln!(
                out,
                "- `{}`{}",
                v.name,
                if v.materialized {
                    " (materialized)"
                } else {
                    ""
                }
            );
        }
        out.push('\n');
    }
    if !schema.enums.is_empty() {
        out.push_str("### Enums\n\n");
        for e in &schema.enums {
            let values: Vec<String> = e.values.iter().map(|v| format!("`{v}`")).collect();
            let _ = writeln!(out, "- `{}`: {}", e.name, values.join(", "));
        }
        out.push('\n');
    }
    if !schema.objects.is_empty() {
        out.push_str("### Other objects\n\n");
        for o in &schema.objects {
            match &o.table {
                Some(t) => {
                    let _ = writeln!(out, "- {} `{}` on `{t}`", o.kind, o.name);
                }
                None => {
                    let _ = writeln!(out, "- {} `{}`", o.kind, o.name);
                }
            }
        }
        out.push('\n');
    }
}

fn table_section(table: &Table, out: &mut String) {
    let _ = writeln!(out, "### `{}`\n", table.name);
    if let Some(comment) = &table.comment {
        let _ = writeln!(out, "> {comment}\n");
    }
    out.push_str("| column | type | null | default | notes |\n|---|---|---|---|---|\n");
    for c in &table.columns {
        let mut notes = Vec::new();
        if table.primary_key.contains(&c.name) {
            notes.push("PK".to_string());
        }
        if c.auto_increment {
            notes.push("auto increment".into());
        }
        if let Some(g) = &c.generated {
            notes.push(g.clone());
        }
        if let Some(u) = &c.on_update {
            notes.push(format!("on update {u}"));
        }
        if let Some(cs) = &c.charset {
            notes.push(format!("charset {cs}"));
        }
        if let Some(cmt) = &c.comment {
            notes.push(format!("“{cmt}”"));
        }
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {} | {} |",
            c.name,
            c.data_type,
            if c.nullable { "yes" } else { "no" },
            c.default
                .as_deref()
                .map(|d| format!("`{d}`"))
                .unwrap_or_default(),
            notes.join(", ").replace('|', "\\|")
        );
    }
    out.push('\n');

    let mut extras = Vec::new();
    if table.primary_key.len() > 1 {
        extras.push(format!("Primary key: ({})", table.primary_key.join(", ")));
    }
    for i in &table.indexes {
        extras.push(format!(
            "{}{}: ({}){}",
            if i.unique { "Unique index" } else { "Index" },
            i.name
                .as_ref()
                .map(|n| format!(" `{n}`"))
                .unwrap_or_default(),
            i.columns.join(", "),
            i.predicate
                .as_ref()
                .map(|p| format!(" where {p}"))
                .unwrap_or_default()
        ));
    }
    for fk in &table.foreign_keys {
        extras.push(format!(
            "Foreign key{}: ({}) → `{}` ({}){}",
            fk.name
                .as_ref()
                .map(|n| format!(" `{n}`"))
                .unwrap_or_default(),
            fk.columns.join(", "),
            fk.references_table,
            fk.references_columns.join(", "),
            fk.on_delete
                .as_ref()
                .map(|a| format!(" on delete {a}"))
                .unwrap_or_default()
        ));
    }
    for c in &table.checks {
        extras.push(format!(
            "Check{}: `{}`",
            c.name
                .as_ref()
                .map(|n| format!(" `{n}`"))
                .unwrap_or_default(),
            c.expr
        ));
    }
    if !table.options.is_empty() {
        let opts: Vec<String> = table
            .options
            .iter()
            .map(|(k, v)| format!("{k}={v}"))
            .collect();
        extras.push(format!("Options: {}", opts.join(", ")));
    }
    if table.row_level_security {
        extras.push("Row level security: enabled".into());
    }
    for e in extras {
        let _ = writeln!(out, "- {}", e.replace('|', "\\|"));
    }
    if !table.indexes.is_empty()
        || !table.foreign_keys.is_empty()
        || !table.checks.is_empty()
        || !table.options.is_empty()
        || table.primary_key.len() > 1
        || table.row_level_security
    {
        out.push('\n');
    }
}

fn compat(c: &Compat) -> String {
    match c.reason() {
        Some(r) => format!("{} ({r})", c.label()),
        None => c.label().to_string(),
    }
}

fn migration(m: &MigrationReport, out: &mut String) {
    let _ = writeln!(out, "### {}\n", m.id);
    let _ = writeln!(out, "- **Deploy:** {}", m.phase);
    let _ = writeln!(
        out,
        "- **Reversible:** {}{}",
        m.reversibility.label(),
        m.reversibility
            .reason()
            .map(|r| format!(" ({r})"))
            .unwrap_or_default()
    );
    let _ = writeln!(out, "- **Backward compatible:** {}", compat(&m.backward));
    let _ = writeln!(out, "- **Forward compatible:** {}", compat(&m.forward));
    let undo = match (&m.provided_undo, &m.generated_undo) {
        (Some(check), _) if check.restores_schema() => format!(
            "provided, restores the schema (undo itself: {})",
            check.reversibility.label()
        ),
        (Some(check), _) => format!(
            "provided, **does not restore the schema**: {}",
            check.differences.join("; ")
        ),
        (None, GeneratedUndo::Generated(_)) => {
            "none provided; rustable can generate one".to_string()
        }
        (None, GeneratedUndo::NotTrivial(reasons)) => {
            format!("none, and not trivial to generate: {}", reasons.join("; "))
        }
    };
    let _ = writeln!(out, "- **Undo:** {}", undo.replace('\n', " "));
    out.push('\n');

    if m.steps.is_empty() {
        out.push_str("_No statements._\n\n");
        return;
    }
    for (i, step) in m.steps.iter().enumerate() {
        let mut flags = Vec::new();
        if !step.reversibility.is_lossless() {
            flags.push(step.reversibility.label().to_string());
        }
        if !step.backward.is_yes() {
            flags.push(format!("backward: {}", step.backward.label()));
        }
        if !step.forward.is_yes() {
            flags.push(format!("forward: {}", step.forward.label()));
        }
        let _ = writeln!(
            out,
            "{}. line {}: {}{}",
            i + 1,
            step.line,
            step.change.to_string().replace('\n', " "),
            if flags.is_empty() {
                String::new()
            } else {
                format!(" _[{}]_", flags.join(", "))
            }
        );
    }
    out.push('\n');
}
