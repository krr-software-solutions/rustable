//! Plan a migration that takes the schema the migrations produce to the schema the code wants.
//!
//! The planner works on two [`Schema`]s: `current` (from folding the migrations, i.e.
//! `schema.toml`) and `desired` (from the code's table definitions, i.e.
//! `code.current_schema.toml`). It produces the [`Change`]s that close the gap, the SQL for them,
//! and a list of **outstanding** differences it deliberately didn't act on.
//!
//! With [`PlanOptions::soft_drops`], nothing is ever dropped: a column the code no longer has is
//! made nullable (so the code's INSERTs keep working) or, if it already is, left alone; a table
//! the code no longer has is left in place. Each of those is recorded as outstanding, so a human
//! can drop it later in a deliberate contract migration.

use std::collections::BTreeSet;

use crate::change::Change;
use crate::dialect::Dialect;
use crate::schema::{Column, Schema, Table};
use crate::undo::forward_sql;

#[derive(Clone, Copy, Debug, Default)]
pub struct PlanOptions {
    /// Never drop tables or columns: make them nullable / leave them, and report them.
    pub soft_drops: bool,
}

#[derive(Clone, Debug, Default)]
pub struct Plan {
    pub changes: Vec<Change>,
    /// One entry per change, in order (several SQL statements for some changes).
    pub sql: Vec<String>,
    /// Differences left for a human: soft drops, things rustable can't render, primary key changes…
    pub outstanding: Vec<String>,
}

impl Plan {
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.changes.is_empty()
    }

    /// The plan as a migration script.
    #[must_use]
    pub fn script(&self) -> String {
        let mut out = String::from(
            "-- Generated by `rustable plan`: brings the migrations in line with the code's tables.\n",
        );
        if !self.outstanding.is_empty() {
            out.push_str("--\n-- Left outstanding (see the outstanding-differences report):\n");
            for o in &self.outstanding {
                out.push_str(&format!("--   - {o}\n"));
            }
        }
        for sql in &self.sql {
            out.push('\n');
            out.push_str(sql);
            out.push_str(";\n");
        }
        out
    }
}

/// Plan the changes from `current` to `desired`.
#[must_use]
pub fn plan(current: &Schema, desired: &Schema, dialect: Dialect, options: PlanOptions) -> Plan {
    let mut plan = Plan::default();
    let mut push = |plan: &mut Plan, change: Change| match forward_sql(&change, dialect) {
        Some(sql) => {
            plan.sql.extend(sql);
            plan.changes.push(change);
        }
        None => plan.outstanding.push(format!(
            "{change}: rustable can't write SQL for this in {dialect}"
        )),
    };

    let names = |s: &Schema| {
        s.tables
            .iter()
            .map(|t| t.name.clone())
            .collect::<BTreeSet<_>>()
    };
    let (have, want) = (names(current), names(desired));

    // New tables first, in an order that respects foreign keys between them.
    for table in order_by_foreign_keys(
        desired
            .tables
            .iter()
            .filter(|t| !have.contains(&t.name))
            .collect(),
    ) {
        push(
            &mut plan,
            Change::CreateTable {
                table: table.clone(),
            },
        );
    }

    for name in have.intersection(&want) {
        if let (Some(a), Some(b)) = (current.table(name), desired.table(name)) {
            plan_table(a, b, options, &mut plan, &mut push);
        }
    }

    for name in have.difference(&want) {
        let table = current.table(name).cloned().unwrap_or_default();
        if options.soft_drops {
            plan.outstanding.push(format!(
                "table `{name}` is not in the code: left in place (drop it in a later migration)"
            ));
        } else {
            push(&mut plan, Change::DropTable { table });
        }
    }

    // Enums: create missing ones, add missing values; removed values/enums are outstanding.
    for e in &desired.enums {
        match current.enums.iter().find(|x| x.name == e.name) {
            None => push(
                &mut plan,
                Change::CreateEnum {
                    enum_type: e.clone(),
                },
            ),
            Some(existing) => {
                for v in e.values.iter().filter(|v| !existing.values.contains(v)) {
                    push(
                        &mut plan,
                        Change::AddEnumValue {
                            name: e.name.clone(),
                            value: v.clone(),
                        },
                    );
                }
                for v in existing.values.iter().filter(|v| !e.values.contains(v)) {
                    plan.outstanding.push(format!(
                        "enum `{}` has value '{v}' that the code doesn't",
                        e.name
                    ));
                }
            }
        }
    }
    plan
}

fn plan_table(
    current: &Table,
    desired: &Table,
    options: PlanOptions,
    plan: &mut Plan,
    push: &mut impl FnMut(&mut Plan, Change),
) {
    let t = &desired.name;

    // Indexes/constraints that change or go away are dropped before columns change under them.
    for index in current
        .indexes
        .iter()
        .filter(|i| !desired.indexes.contains(i))
    {
        push(
            plan,
            Change::DropIndex {
                table: t.clone(),
                index: index.clone(),
            },
        );
    }
    for fk in current
        .foreign_keys
        .iter()
        .filter(|f| !desired.foreign_keys.contains(f))
    {
        push(
            plan,
            Change::DropForeignKey {
                table: t.clone(),
                fk: fk.clone(),
            },
        );
    }
    for check in current
        .checks
        .iter()
        .filter(|c| !desired.checks.contains(c))
    {
        push(
            plan,
            Change::DropCheck {
                table: t.clone(),
                check: check.clone(),
            },
        );
    }

    for (position, column) in desired.columns.iter().enumerate() {
        match current.column(&column.name) {
            None => {
                if !column.nullable
                    && column.default.is_none()
                    && !column.auto_increment
                    && column.generated.is_none()
                {
                    plan.outstanding.push(format!(
                        "`{t}.{}` is NOT NULL without a default: existing rows need a backfill before this can apply",
                        column.name
                    ));
                }
                push(
                    plan,
                    Change::AddColumn {
                        table: t.clone(),
                        column: column.clone(),
                        position,
                    },
                );
            }
            Some(existing) if existing != column => push(
                plan,
                Change::AlterColumn {
                    table: t.clone(),
                    before: existing.clone(),
                    after: column.clone(),
                },
            ),
            Some(_) => {}
        }
    }

    for (position, column) in current.columns.iter().enumerate() {
        if desired.column(&column.name).is_some() {
            continue;
        }
        if !options.soft_drops {
            push(
                plan,
                Change::DropColumn {
                    table: t.clone(),
                    column: column.clone(),
                    position,
                },
            );
        } else if !column.nullable && !current.primary_key.contains(&column.name) {
            push(
                plan,
                Change::AlterColumn {
                    table: t.clone(),
                    before: column.clone(),
                    after: Column {
                        nullable: true,
                        ..column.clone()
                    },
                },
            );
            plan.outstanding.push(format!(
                "column `{t}.{}` is not in the code: made nullable instead of dropped",
                column.name
            ));
        } else {
            plan.outstanding.push(format!(
                "column `{t}.{}` is not in the code: left in place",
                column.name
            ));
        }
    }

    if current.primary_key != desired.primary_key {
        plan.outstanding.push(format!(
            "primary key of `{t}` differs: ({}) in migrations vs ({}) in code",
            current.primary_key.join(", "),
            desired.primary_key.join(", ")
        ));
    }

    for index in desired
        .indexes
        .iter()
        .filter(|i| !current.indexes.contains(i))
    {
        push(
            plan,
            Change::AddIndex {
                table: t.clone(),
                index: index.clone(),
            },
        );
    }
    for fk in desired
        .foreign_keys
        .iter()
        .filter(|f| !current.foreign_keys.contains(f))
    {
        push(
            plan,
            Change::AddForeignKey {
                table: t.clone(),
                fk: fk.clone(),
            },
        );
    }
    for check in desired
        .checks
        .iter()
        .filter(|c| !current.checks.contains(c))
    {
        push(
            plan,
            Change::AddCheck {
                table: t.clone(),
                check: check.clone(),
            },
        );
    }
}

/// Order new tables so a table comes after the tables its foreign keys reference.
fn order_by_foreign_keys(mut pending: Vec<&Table>) -> Vec<&Table> {
    pending.sort_by(|a, b| a.name.cmp(&b.name));
    let mut out: Vec<&Table> = Vec::new();
    while !pending.is_empty() {
        let ready = pending.iter().position(|t| {
            t.foreign_keys.iter().all(|fk| {
                fk.references_table == t.name
                    || !pending.iter().any(|p| p.name == fk.references_table)
            })
        });
        // A cycle: just take the next one (its FKs will fail until the other table exists).
        let i = ready.unwrap_or(0);
        out.push(pending.remove(i));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::apply::apply_all;
    use crate::statements::split_and_parse;

    fn schema(sql: &str) -> Schema {
        let mut s = Schema::default();
        apply_all(
            &mut s,
            &split_and_parse(sql, Dialect::Postgres),
            Dialect::Postgres,
        );
        s
    }

    #[test]
    fn plans_and_soft_drops() {
        let current = schema(
            "CREATE TABLE users (id bigint PRIMARY KEY, email text NOT NULL, legacy text NOT NULL, notes text);",
        );
        let desired = schema(
            "CREATE TABLE users (id bigint PRIMARY KEY, email text NOT NULL, name text);
             CREATE TABLE posts (id bigint PRIMARY KEY, user_id bigint REFERENCES users (id));",
        );

        let hard = plan(
            &current,
            &desired,
            Dialect::Postgres,
            PlanOptions::default(),
        );
        let script = hard.script();
        assert!(
            script.contains("ALTER TABLE users DROP COLUMN legacy;"),
            "{script}"
        );
        assert!(
            script.contains("ALTER TABLE users ADD COLUMN name TEXT"),
            "{script}"
        );
        assert!(script.contains("CREATE TABLE posts"), "{script}");

        let soft = plan(
            &current,
            &desired,
            Dialect::Postgres,
            PlanOptions { soft_drops: true },
        );
        let script = soft.script();
        assert!(!script.contains("DROP COLUMN"), "{script}");
        assert!(
            script.contains("ALTER TABLE users ALTER COLUMN legacy DROP NOT NULL;"),
            "{script}"
        );
        assert_eq!(soft.outstanding.len(), 2, "{:#?}", soft.outstanding);

        // Applying the plan to the current schema must give the desired schema
        // (up to the columns soft drops deliberately left behind).
        let mut applied = current.clone();
        apply_all(
            &mut applied,
            &split_and_parse(&hard.script(), Dialect::Postgres),
            Dialect::Postgres,
        );
        assert!(
            crate::diff::diff(&desired, &applied).is_empty(),
            "{:#?}",
            crate::diff::diff(&desired, &applied)
        );
    }
}
