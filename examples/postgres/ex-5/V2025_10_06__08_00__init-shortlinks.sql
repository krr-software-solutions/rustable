/*
 * snip.ly -- URL shortener, initial schema.
 *
 * Everything in one file because the service launched with exactly this shape.
 * Multi-statement, mixes DDL, a plpgsql function and a trigger.
 */

CREATE TYPE link_visibility AS ENUM ('public', 'unlisted', 'private');

CREATE TABLE links (
    id          bigint          GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    code        varchar(16)     NOT NULL UNIQUE CHECK (code ~ '^[A-Za-z0-9_-]+$'),
    target_url  text            NOT NULL,
    visibility  link_visibility NOT NULL DEFAULT 'public',
    hit_count   bigint          NOT NULL DEFAULT 0,
    expires_at  timestamptz,
    created_at  timestamptz     NOT NULL DEFAULT now(),
    CONSTRAINT links_expiry_in_future CHECK (expires_at IS NULL OR expires_at > created_at)
);

CREATE TABLE link_hits (
    id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    link_id    bigint      NOT NULL REFERENCES links (id) ON DELETE CASCADE,
    referrer   text,
    user_agent text,
    hit_at     timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX link_hits_link_id_hit_at_idx ON link_hits (link_id, hit_at DESC);
-- Only non-expiring links are served from the hot cache; index just those.
CREATE INDEX links_never_expire_idx ON links (code) WHERE expires_at IS NULL;

-- Keep links.hit_count denormalised so the redirect path never aggregates.
CREATE FUNCTION bump_link_hit_count() RETURNS trigger
LANGUAGE plpgsql AS $fn$
BEGIN
    UPDATE links SET hit_count = hit_count + 1 WHERE id = NEW.link_id;
    RETURN NULL; -- AFTER trigger: return value ignored
END;
$fn$;

CREATE TRIGGER link_hits_bump_count
    AFTER INSERT ON link_hits
    FOR EACH ROW EXECUTE FUNCTION bump_link_hit_count();

COMMENT ON TABLE links IS 'One row per short code.';
COMMENT ON COLUMN links.hit_count IS 'Maintained by trigger link_hits_bump_count; do not write directly.';
